import datetime

from airflow.decorators import dag, task


default_args = {
    "owner": "Lourdes Tolotto",
    "depends_on_past": False,
    "retries": 1,
    "retry_delay": datetime.timedelta(minutes=5),
}


@dag(
    dag_id="train_student_performance",
    description="Train and register the Student Performance model.",
    default_args=default_args,
    schedule=None,
    catchup=False,
    tags=["Training", "Student Performance"],
)
def train_student_performance():

    @task.virtualenv(
        requirements=["boto3"],
        system_site_packages=True,
    )
    def get_latest_dataset() -> str:
        "Return the latest Student Performance dataset folder from MinIO."
        import os
        import boto3

        # Connect to MinIO using S3-compatible credentials
        s3 = boto3.client(
            "s3",
            endpoint_url=os.getenv("AWS_ENDPOINT_URL_S3"),
            aws_access_key_id=os.getenv("AWS_ACCESS_KEY_ID"),
            aws_secret_access_key=os.getenv("AWS_SECRET_ACCESS_KEY"),
        )

        # List all available Student Performance dataset folders
        response = s3.list_objects_v2(
            Bucket="data",
            Prefix="student_performance/",
            Delimiter="/",
        )

        folders = [
            item["Prefix"].rstrip("/").split("/")[-1]
            for item in response.get("CommonPrefixes", [])
        ]

        if not folders:
            raise ValueError("No Student Performance datasets found in MinIO.")

        # Dataset folders are timestamped, so max() returns the latest one
        latest_folder = max(folders)
        print(f"Latest dataset: {latest_folder}")

        return latest_folder

    @task.virtualenv(
        requirements=[
            "awswrangler==3.6.0",
            "scikit-learn==1.3.2",
            "mlflow==2.10.2",
            "optuna>=4.0.0",
            "numpy<2",
        ],
        system_site_packages=True,
    )
    def train_model(dataset_folder: str) -> None:
        "Train, evaluate and register the Student Performance model."
        import awswrangler as wr
        import mlflow
        import mlflow.sklearn
        import numpy as np
        import optuna

        from mlflow.models import infer_signature
        from sklearn.linear_model import LogisticRegression
        from sklearn.metrics import (
            accuracy_score,
            f1_score,
            precision_score,
            recall_score,
        )
        from sklearn.model_selection import cross_val_score

        # Load the train/test datasets generated by the ETL
        base_path = f"s3://data/student_performance/{dataset_folder}"

        X_train = wr.s3.read_csv(f"{base_path}/X_train.csv")
        X_test = wr.s3.read_csv(f"{base_path}/X_test.csv")
        y_train = wr.s3.read_csv(f"{base_path}/y_train.csv").squeeze("columns")
        y_test = wr.s3.read_csv(f"{base_path}/y_test.csv").squeeze("columns")

        print(f"Train shape: {X_train.shape}")
        print(f"Test shape: {X_test.shape}")

        # Configure the MLflow experiment
        mlflow.set_tracking_uri("http://mlflow:5000")
        experiment = mlflow.set_experiment("Student Performance - Training")

        # Optuna tries different hyperparameters and maximizes weighted F1
        def objective(trial):
            C = trial.suggest_float("C", 1e-4, 1e2, log=True)
            solver = trial.suggest_categorical("solver", ["lbfgs", "saga"])

            model = LogisticRegression(
                C=C,
                solver=solver,
                max_iter=1000,
                random_state=42,
            )

            score = cross_val_score(
                model,
                X_train,
                y_train,
                cv=5,
                scoring="f1_weighted",
            ).mean()

            return float(score)

        # One MLflow run contains the full training process
        with mlflow.start_run(
            experiment_id=experiment.experiment_id,
            run_name=f"training_{dataset_folder}",
        ):
            # Search for the best Logistic Regression hyperparameters
            study = optuna.create_study(direction="maximize")
            study.optimize(objective, n_trials=10)

            print(f"Best parameters: {study.best_params}")
            print(f"Best CV F1: {study.best_value:.4f}")

            # Train the final model using the best parameters
            model = LogisticRegression(
                **study.best_params,
                max_iter=1000,
                random_state=42,
            )

            model.fit(X_train, y_train)

            # Evaluate the model on the test set
            y_pred = model.predict(X_test)

            metrics = {
                "accuracy": accuracy_score(y_test, y_pred),
                "f1_weighted": f1_score(
                    y_test,
                    y_pred,
                    average="weighted",
                ),
                "precision_weighted": precision_score(
                    y_test,
                    y_pred,
                    average="weighted",
                    zero_division=0,
                ),
                "recall_weighted": recall_score(
                    y_test,
                    y_pred,
                    average="weighted",
                    zero_division=0,
                ),
                "best_cv_f1": study.best_value,
            }

            # Log parameters and metrics to MLflow
            mlflow.log_param("model", "LogisticRegression")
            mlflow.log_param("dataset_folder", dataset_folder)
            mlflow.log_params(study.best_params)
            mlflow.log_metrics(metrics)

            # Register the trained model in the MLflow Model Registry
            signature = infer_signature(
                X_train,
                model.predict(X_train),
            )

            mlflow.sklearn.log_model(
                sk_model=model,
                artifact_path="model",
                registered_model_name="student_performance_model",
                signature=signature,
            )

            print("Model trained and registered successfully.")

    # DAG dependency: first find the latest dataset, then train the model
    latest_dataset = get_latest_dataset()
    train_model(latest_dataset)


dag = train_student_performance()